def main():
    seen_properties = load_seen_properties()

    if "--weekly-digest" in sys.argv:
        print("📊 Sending weekly digest report...")
        send_weekly_digest(seen_properties)
        return

    print("🚀 Starting Farmland Monitor multi-site check (10+ Acre Filter)...")
    
    # 1. Scrape web platforms
    for county in TARGET_COUNTIES:
        check_landwatch_for_county(county, seen_properties)
        check_landandfarm_for_county(county, seen_properties)
        check_whitetail_properties(county, seen_properties)

    # 2. Process incoming Zillow saved search emails
    check_zillow_emails(seen_properties)

    print("\n✅ Execution completed successfully.")

if __name__ == "__main__":
    main()
