# ZILLOW EMAIL IMAP READER
# ==========================================
def check_zillow_emails(seen_properties):
    print("🔍 Checking Gmail inbox for Zillow alert emails...")
    try:
        mail = imaplib.IMAP4_SSL("imap.gmail.com")
        mail.login(SENDER_EMAIL, SENDER_PASSWORD)
        mail.select("inbox")

        # Search for unread emails from Zillow
        status, messages = mail.search(None, '(UNSEEN FROM "zillow.com")')
        if status != "OK" or not messages[0]:
            print("  No new unread Zillow alert emails found.")
            mail.logout()
            return

        email_ids = messages[0].split()
        new_found_count = 0

        for e_id in email_ids:
            _, msg_data = mail.fetch(e_id, "(RFC822)")
            for response_part in msg_data:
                if isinstance(response_part, tuple):
                    msg = email.message_from_bytes(response_part[1])
                    
                    # Extract email body (HTML)
                    body = ""
                    if msg.is_multipart():
                        for part in msg.walk():
                            if part.get_content_type() == "text/html":
                                body = part.get_payload(decode=True).decode("utf-8", errors="ignore")
                                break
                    else:
                        body = msg.get_payload(decode=True).decode("utf-8", errors="ignore")

                    # Extract all Zillow homedetails property links
                    zillow_links = re.findall(r'https://www\.zillow\.com/homedetails/[^"\s\'>]+', body)
                    
                    for raw_url in zillow_links:
                        # Clean tracking parameters from URL
                        clean_url = raw_url.split("?")[0]
                        
                        if clean_url not in seen_properties:
                            print(f"\n🚨 NEW ZILLOW FSBO/LISTING FOUND VIA EMAIL!")
                            title = "Zillow Land Listing (Saved Search Alert)"
                            send_rich_email_alert(title, clean_url, "Monitored Region", "Zillow")
                            save_seen_property(clean_url)
                            seen_properties.add(clean_url)
                            new_found_count += 1

            # Mark email as read
            mail.store(e_id, '+FLAGS', '\\Seen')

        mail.logout()
        if new_found_count == 0:
            print("  Zillow emails processed, but no new unique property links were found.")

    except Exception as e:
        print(f"⚠️ Error reading Zillow emails via IMAP: {e}")

